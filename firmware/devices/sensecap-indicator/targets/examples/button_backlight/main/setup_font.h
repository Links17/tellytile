static const uint8_t *glyph(unsigned char c)
{
    if (c >= 'a' && c <= 'z') c = c - 'a' + 'A';
    if (c >= 'A' && c <= 'Z') return letters[c - 'A'];
    if (c >= '0' && c <= '9') return numbers[c - '0'];
    return punctuation[c < 128 ? c : '?'];
}
